const SKILLS = [
  {
    name: "Python",
    logo: <PythonLogo />,
  },
  {
    name: "n8n",
    logo: <N8nLogo />,
  },
];

const TABS = ["Code", "Hardware"] as const;

export function Skills() {
  const [tab, setTab] = useState<(typeof TABS)[number]>("Code");

  return (
    <section id="skills" className="bg-bg px-6 py-24 text-fg sm:py-32">
      <div className="mx-auto w-full max-w-5xl">
        <p className="text-xs tracking-widest text-muted uppercase">Skills</p>
        <div role="tablist" aria-label="Skills" className="mt-6 flex gap-6">
          {TABS.map((name) => {
            const selected = tab === name;
            return (
              <button
                key={name}
                type="button"
                role="tab"
                id={`tab-${name}`}
                aria-selected={selected}
                aria-controls={`panel-${name}`}
                onClick={() => setTab(name)}
                className={`border-b pb-2 text-xs tracking-widest uppercase ${selected ? "border-fg text-fg" : "border-transparent text-muted"}`}
              >
                {name}
              </button>
            );
          })}
        </div>
        {tab === "Code" ? (
          <ul
            id="panel-Code"
            role="tabpanel"
            aria-labelledby="tab-Code"
            className="mt-10 grid max-w-3xl gap-4 sm:grid-cols-2"
          >
            {SKILLS.map((skill) => (
              <li
                key={skill.name}
                className="flex flex-col items-start border border-line px-6 py-8"
              >
                {skill.logo}
                <h2 className="mt-8 text-lg font-medium tracking-wide">{skill.name}</h2>
              </li>
            ))}
          </ul>
        ) : (
          <ul
            id="panel-Hardware"
            role="tabpanel"
            aria-labelledby="tab-Hardware"
            className="mt-10 grid max-w-sm gap-4"
          >
            <li className="flex flex-col items-start border border-line px-6 py-8">
              <KiCadLogo />
              <h2 className="mt-8 text-lg font-medium tracking-wide">KiCad</h2>
            </li>
          </ul>
        )}
      </div>
    </section>
  );
}
